import { backup, DatabaseSync } from 'node:sqlite';
import { chmodSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { readConfig } from '../src/config.js';
import { openDatabase } from '../src/db.js';
import { pruneManagedBackups, pruneTransientData } from '../src/retention.js';
const config=readConfig(), db=openDatabase(config.dbPath);
const target=resolve(process.argv[2] || `${dirname(config.dbPath)}/backups/bezreszty-${new Date().toISOString().replaceAll(':','-')}.sqlite`);
if(target===resolve(config.dbPath))throw new Error('Kopia nie może nadpisać aktywnej bazy.');
pruneTransientData(db);pruneManagedBackups(config.dbPath);
mkdirSync(dirname(target),{recursive:true,mode:0o700});
await backup(db,target);chmodSync(target,0o600);
const copy=new DatabaseSync(target);
copy.exec('DELETE FROM bank_mail_quarantine; VACUUM');copy.close();
db.close();console.log(`Kopia bazy: ${target}`);
