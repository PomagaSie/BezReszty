// Builds the browser bundle of the campaign story editor (TipTap + ProseMirror) into public/vendor/.
// The result is committed, so the production image needs no build step. Run `npm run build:editor` after changing client/.
import { build } from 'esbuild';
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const outfile = join(root, 'public/vendor/story-editor.js');
const result = await build({
  entryPoints: [join(root, 'client/story-editor.js')], outfile, bundle: true, minify: true, format: 'iife', target: ['es2020'],
  legalComments: 'none', metafile: true, logLevel: 'info',
  banner: { js: '/* BezReszty story editor: TipTap 3 + ProseMirror. Generated by scripts/build-editor.mjs; licences: story-editor.LICENSE.txt */' },
});

// Collect the licence of every npm package that ended up in the bundle.
const packages = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  const match = input.match(/node_modules\/((?:@[^/]+\/)?[^/]+)\//);
  if (!match || packages.has(match[1])) continue;
  const directory = join(root, 'node_modules', match[1]);
  const manifest = JSON.parse(readFileSync(join(directory, 'package.json'), 'utf8'));
  const file = readdirSync(directory).find(name => /^(licen[cs]e|copying)(\.|$)/i.test(name));
  packages.set(match[1], { version: manifest.version, license: manifest.license, text: file ? readFileSync(join(directory, file), 'utf8').trim() : '' });
}
const lines = ['Third-party software bundled into public/vendor/story-editor.js', 'Built by scripts/build-editor.mjs with esbuild. Packages and their licences:', ''];
for (const [name, info] of [...packages].sort(([a], [b]) => a.localeCompare(b))) {
  lines.push('='.repeat(78), `${name} ${info.version} (${info.license})`, '', info.text || `Licensed under ${info.license}; see the package on npm.`, '');
}
writeFileSync(join(root, 'public/vendor/story-editor.LICENSE.txt'), lines.join('\n'));
console.log(`${packages.size} packages, licences written`);
